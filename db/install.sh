#!/usr/bin/env bash
# =============================================================================
# install.sh — Curator one-shot fresh install
# =============================================================================
# Run from the repo root:
#
#   cp install.conf.example install.conf
#   # Edit install.conf with real passwords and settings
#   bash db/install.sh
#
# What this script does:
#   1. Reads install.conf for passwords and install preferences
#   2. Writes .env for docker compose
#   3. Fetches the SQL init files from the steward GitHub repo into db/init/
#   4. Optionally starts the containers (RUN_COMPOSE=true in install.conf)
#   5. Deletes install.conf — its absence signals the install is complete
#
# This is a one-shot script for a fresh server. It does not update an
# existing database. For the planned re-runnable variant see:
#   docs/roadmap/TODO_STEWARD_TIDY_UP.md → "Install script (curator)"
#
# Requirements: bash 4+, curl
# =============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
CONF="$REPO_ROOT/install.conf"
INIT_DIR="$SCRIPT_DIR/init"
ENV_FILE="$REPO_ROOT/.env"


# ---- Load config -------------------------------------------------------------

if [[ ! -f "$CONF" ]]; then
  echo "Error: install.conf not found."
  echo ""
  echo "  cp install.conf.example install.conf"
  echo "  # Fill in real values"
  echo "  bash db/install.sh"
  exit 1
fi

# shellcheck source=/dev/null
source "$CONF"


# ---- Validate required values ------------------------------------------------

required_vars=(
  POSTGRES_DB POSTGRES_USER POSTGRES_PASSWORD
  WEB_APP_USER_PASSWORD APP_PORT
)
missing=()
for var in "${required_vars[@]}"; do
  if [[ -z "${!var:-}" ]]; then
    missing+=("$var")
  fi
done
if [[ ${#missing[@]} -gt 0 ]]; then
  echo "Error: missing required values in install.conf:"
  for var in "${missing[@]}"; do
    echo "  $var"
  done
  exit 1
fi

STEWARD_BRANCH="${STEWARD_BRANCH:-main}"
RUN_COMPOSE="${RUN_COMPOSE:-false}"


# ---- Write .env --------------------------------------------------------------

echo "Writing .env..."

cat > "$ENV_FILE" <<EOF
# Generated by db/install.sh — do not edit by hand.
# To change values: update install.conf and re-run the install,
# or edit this file directly and run: docker compose up --build -d

POSTGRES_DB=$POSTGRES_DB
POSTGRES_USER=$POSTGRES_USER
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
WEB_APP_USER_PASSWORD=$WEB_APP_USER_PASSWORD
APP_PORT=$APP_PORT
EOF

echo "  .env written."


# ---- Fetch SQL init files from steward --------------------------------------

RAW_BASE="https://raw.githubusercontent.com/carolynboyle/steward/${STEWARD_BRANCH}/databases/wcyj/sql"

# Files listed in the order Docker will execute them (alphabetical by name).
# Excludes one-time migrations (03b, 05b) and the drop script (00_drop).
# To add a new file: append it in the correct sort position.
# If steward is ever made private, add GITHUB_TOKEN= to install.conf and
# pass -H "Authorization: token $GITHUB_TOKEN" on each curl call below.
# See docs/roadmap/TODO_STEWARD_TIDY_UP.md → "Make the repo private".
SQL_FILES=(
  01_audit.sql
  02_identity.sql
  03_projects.sql
  04_infrastructure.sql
  05_seed.sql
  06_api.sql
  06c_api_identity.sql
  06e_api_tasks.sql
  06f_api_project_links.sql
  07a_detail_views.sql
  07b_detail_api.sql
  07c_seanchai.sql
  07d_seanchai_fix.sql
  07e_seanchai_list_api.sql
  08_field_schema.sql
  08b_api_lookup.sql
  10d_seanchai_todos.sql
  10f_seanchai_autonumber.sql
  10g_seanchai_other_type.sql
  10h_crew_role_seanchai.sql
  10i_seanchai_todos_to_tasks.sql
)

echo "Fetching ${#SQL_FILES[@]} SQL files from steward (branch: ${STEWARD_BRANCH})..."

for f in "${SQL_FILES[@]}"; do
  echo "  → $f"
  curl --silent --show-error --fail \
    "${RAW_BASE}/${f}" \
    --output "${INIT_DIR}/${f}"
done

echo "  SQL files written to db/init/."


# ---- Start containers (optional) ---------------------------------------------

if [[ "$RUN_COMPOSE" == "true" ]]; then
  echo "Starting containers..."
  docker compose --project-directory "$REPO_ROOT" up --build -d
  echo "  Containers started."
fi


# ---- Done — remove install.conf ----------------------------------------------

rm "$CONF"

echo ""
echo "Install complete. install.conf removed."
if [[ "$RUN_COMPOSE" != "true" ]]; then
  echo "When ready: docker compose up --build -d"
fi
